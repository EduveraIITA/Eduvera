const utilityGlyphs = {
  back: ArrowLeftIcon,
  arrow: ArrowRightIcon,
  search: MagnifyingGlassIcon,
  close: XIcon,
  chevron: CaretRightIcon,
 } as const;

/** Flat area-coloured symbols; utilities, status and brand retain their meanings. */
export function Icon({ name, size = 28, muted = false, color, area, destination }: { name: string; size?: number; muted?: boolean; color?: string; area?: ProductIconIdentity; destination?: string }) {
  const { colors, dark } = useTheme();
  const utility = Object.hasOwn(utilityGlyphs, name) ? utilityGlyphs[name as keyof typeof utilityGlyphs] : undefined;
  if (utility) { const Glyph = utility; return <Glyph size={size} color={color ?? (muted ? colors.muted : colors.link)} weight="regular" />; }
  const [glyph, identity] = Object.hasOwn(productIconDefinitions, name) ? productIconDefinitions[name as keyof typeof productIconDefinitions] : productIconDefinitions.unknown;
  if (glyph === 'Assistant') return <AssistantMark size={size} />;
  const Glyph = glyphs[glyph];
  const resolvedArea = area ?? (destination ? iconAreaForDestination(destination, identity) : identity);
  const appearance = productIconAppearance(muted ? 'neutral' : resolvedArea, colors, dark);
  return <Glyph size={size} color={color ?? appearance.ink} weight="regular" />;
}
