const { createHash } = require('node:crypto');
const { createRequire } = require('node:module');
const { mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } = require('node:fs');
const path = require('node:path');

const mobileRoot = path.resolve(__dirname, '..');
const requireMobile = createRequire(path.join(mobileRoot, 'package.json'));

function writeIfChanged(filename, contents) {
  const data = Buffer.isBuffer(contents) ? contents : Buffer.from(contents);
  try { if (readFileSync(filename).equals(data)) return false; } catch (error) { if (error.code !== 'ENOENT') throw error; }
  mkdirSync(path.dirname(filename), { recursive: true });
  writeFileSync(filename, data);
  return true;
}

/** Match the WASM to Skia's installed dependency; never fetch a CDN latest version. */
function prepareCampusSkiaWeb(options = {}) {
  const skiaPackagePath = requireMobile.resolve('react-native-skia/package.json');
  const requireSkia = createRequire(skiaPackagePath);
  const canvasKitPackagePath = requireSkia.resolve('canvaskit-wasm/package.json');
  const canvasKitRoot = path.dirname(canvasKitPackagePath);
  const { version } = JSON.parse(readFileSync(canvasKitPackagePath, 'utf8'));
  const wasm = readFileSync(path.join(canvasKitRoot, 'bin/full/canvaskit.wasm'));
  if (!wasm.subarray(0, 8).equals(Buffer.from([0, 97, 115, 109, 1, 0, 0, 0]))) throw new Error('Installed CanvasKit WASM is invalid.');
  const sha256 = createHash('sha256').update(wasm).digest('hex');
  const filename = `canvaskit-${version}-${sha256.slice(0, 12)}.wasm`;
  const publicDirectory = options.publicDirectory ?? path.join(mobileRoot, 'public/skia');
  const manifestPath = options.manifestPath ?? path.join(mobileRoot, 'src/features/campus/skia/campusSkiaWebAsset.generated.ts');
  const asset = { version, path: `/skia/${filename}`, sha256, bytes: wasm.length };
  const manifest = `// Generated by scripts/prepare-campus-skia-web.cjs from the installed Skia dependency.\nexport const CAMPUS_SKIA_WEB_ASSET = ${JSON.stringify(asset, null, 2)} as const;\n`;
  writeIfChanged(path.join(publicDirectory, filename), wasm);
  // Only this generator's versioned payloads retire on an upgrade. Preserve all
  // unrelated public assets and the current dependency's exact matching WASM.
  for (const previous of readdirSync(publicDirectory)) if (previous !== filename && /^canvaskit-\d+\.\d+\.\d+-[a-f0-9]{12}\.wasm$/.test(previous)) unlinkSync(path.join(publicDirectory, previous));
  writeIfChanged(path.join(publicDirectory, 'canvaskit-LICENSE.txt'), readFileSync(path.join(canvasKitRoot, 'LICENSE')));
  writeIfChanged(manifestPath, manifest);
  return asset;
}

module.exports = { prepareCampusSkiaWeb };
if (require.main === module) console.log(JSON.stringify(prepareCampusSkiaWeb()));
