  ON event_outbox(sequence);
CREATE INDEX IF NOT EXISTS event_outbox_replay_idx
  ON event_outbox(sequence, created_at)
  WHERE published_at IS NOT NULL;
CREATE INDEX IF NOT EXISTS event_outbox_expiry_idx
  ON event_outbox(expires_at);

CREATE TABLE IF NOT EXISTS attendance_registers (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  school_id uuid NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
  class_section_id uuid NOT NULL REFERENCES class_sections(id) ON DELETE CASCADE,
  term_id uuid NOT NULL REFERENCES academic_terms(id) ON DELETE RESTRICT,
  date date NOT NULL,
  state varchar(16) NOT NULL DEFAULT 'draft' CHECK (state IN ('draft', 'submitted', 'locked')),
  revision integer NOT NULL DEFAULT 0 CHECK (revision >= 0),
  submitted_by uuid REFERENCES users(id) ON DELETE SET NULL,
  submitted_at timestamptz,
  locked_by uuid REFERENCES users(id) ON DELETE SET NULL,
  locked_at timestamptz,
  reopened_by uuid REFERENCES users(id) ON DELETE SET NULL,
  reopened_at timestamptz,
  reopen_reason varchar(500),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((submitted_at IS NULL) = (submitted_by IS NULL)),
  CHECK ((locked_at IS NULL) = (locked_by IS NULL)),
  CHECK (reopen_reason IS NULL OR length(btrim(reopen_reason)) >= 3),
  UNIQUE (class_section_id, term_id, date)
);
CREATE INDEX IF NOT EXISTS attendance_registers_school_date_idx
  ON attendance_registers(school_id, date DESC, class_section_id);

CREATE TABLE IF NOT EXISTS attendance_submissions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  school_id uuid NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
  class_section_id uuid NOT NULL REFERENCES class_sections(id) ON DELETE CASCADE,
  term_id uuid NOT NULL REFERENCES academic_terms(id) ON DELETE RESTRICT,
  date date NOT NULL,
  submitted_by uuid NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  idempotency_key varchar(128) NOT NULL,
  request_hash char(64) NOT NULL,
  request_id uuid NOT NULL,
  register_revision integer NOT NULL CHECK (register_revision > 0),
  records_count integer NOT NULL CHECK (records_count > 0),
  changed_count integer NOT NULL CHECK (changed_count >= 0),
  result_status integer NOT NULL DEFAULT 200 CHECK (result_status BETWEEN 200 AND 599),
  result_body jsonb NOT NULL DEFAULT '{}'::jsonb,
  completed_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (changed_count <= records_count),
  UNIQUE (school_id, submitted_by, idempotency_key)
);
CREATE INDEX IF NOT EXISTS attendance_submissions_register_idx
  ON attendance_submissions(class_section_id, date DESC, created_at DESC);

CREATE TABLE IF NOT EXISTS attendance_record_revisions (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  attendance_record_id uuid NOT NULL REFERENCES attendance_records(id) ON DELETE RESTRICT,
  attendance_submission_id uuid REFERENCES attendance_submissions(id) ON DELETE RESTRICT,
  attendance_register_id uuid REFERENCES attendance_registers(id) ON DELETE RESTRICT,
  school_id uuid NOT NULL REFERENCES schools(id) ON DELETE CASCADE,
  student_id uuid NOT NULL REFERENCES students(id) ON DELETE RESTRICT,
  class_section_id uuid NOT NULL REFERENCES class_sections(id) ON DELETE RESTRICT,
  date date NOT NULL,
  previous_status varchar(16) CHECK (previous_status IS NULL OR previous_status IN ('present', 'absent', 'late', 'excused', 'half_day')),
  new_status varchar(16) NOT NULL CHECK (new_status IN ('present', 'absent', 'late', 'excused', 'half_day')),
  previous_remarks varchar(500),
  new_remarks varchar(500) NOT NULL DEFAULT '',
  previous_check_in_at timestamptz,
  new_check_in_at timestamptz,
  previous_check_out_at timestamptz,
  new_check_out_at timestamptz,
  reason varchar(500) NOT NULL,
  changed_by uuid NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  request_id uuid NOT NULL,
  register_revision integer NOT NULL CHECK (register_revision > 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (length(btrim(reason)) >= 3),
  UNIQUE (request_id, attendance_record_id)
);
CREATE INDEX IF NOT EXISTS attendance_revisions_student_date_idx
  ON attendance_record_revisions(student_id, date DESC, id DESC);
CREATE INDEX IF NOT EXISTS attendance_revisions_register_idx
  ON attendance_record_revisions(class_section_id, date DESC, register_revision);

