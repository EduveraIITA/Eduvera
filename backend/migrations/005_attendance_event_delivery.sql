-- Defense in depth: API authorization is the primary access boundary, while
-- deferred constraint triggers make cross-school relationship corruption
-- impossible even for server-side maintenance jobs and future importers.
CREATE OR REPLACE FUNCTION validate_school_relationships()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  expected_school uuid;
  related_school uuid;
BEGIN
  IF TG_TABLE_NAME = 'enrollments' THEN
    SELECT school_id INTO expected_school FROM students WHERE id=NEW.student_id;
    SELECT school_id INTO related_school FROM class_sections WHERE id=NEW.class_section_id;
    IF expected_school IS DISTINCT FROM related_school THEN RAISE EXCEPTION 'Enrollment student and class must belong to one school' USING ERRCODE='23514'; END IF;
    SELECT school_id INTO related_school FROM academic_terms WHERE id=NEW.term_id;
    IF expected_school IS DISTINCT FROM related_school THEN RAISE EXCEPTION 'Enrollment student and term must belong to one school' USING ERRCODE='23514'; END IF;
  ELSIF TG_TABLE_NAME = 'subject_attendance' THEN
    SELECT school_id INTO expected_school FROM students WHERE id=NEW.student_id;
    SELECT school_id INTO related_school FROM subjects WHERE id=NEW.subject_id;
    IF expected_school IS DISTINCT FROM related_school THEN RAISE EXCEPTION 'Subject attendance student and subject must belong to one school' USING ERRCODE='23514'; END IF;
    SELECT school_id INTO related_school FROM academic_terms WHERE id=NEW.term_id;
    IF expected_school IS DISTINCT FROM related_school THEN RAISE EXCEPTION 'Subject attendance student and term must belong to one school' USING ERRCODE='23514'; END IF;
  ELSIF TG_TABLE_NAME = 'attendance_records' THEN
    SELECT school_id INTO expected_school FROM students WHERE id=NEW.student_id;
    SELECT school_id INTO related_school FROM class_sections WHERE id=NEW.class_section_id;
    IF expected_school IS DISTINCT FROM related_school THEN RAISE EXCEPTION 'Attendance student and class must belong to one school' USING ERRCODE='23514'; END IF;
  ELSIF TG_TABLE_NAME = 'timetable_slots' THEN
    SELECT school_id INTO expected_school FROM class_sections WHERE id=NEW.class_section_id;
    SELECT school_id INTO related_school FROM academic_terms WHERE id=NEW.term_id;
    IF expected_school IS DISTINCT FROM related_school THEN RAISE EXCEPTION 'Timetable class and term must belong to one school' USING ERRCODE='23514'; END IF;
    IF NEW.subject_id IS NOT NULL THEN
      SELECT school_id INTO related_school FROM subjects WHERE id=NEW.subject_id;
      IF expected_school IS DISTINCT FROM related_school THEN RAISE EXCEPTION 'Timetable subject must belong to the class school' USING ERRCODE='23514'; END IF;
    END IF;
    IF NEW.teacher_user_id IS NOT NULL AND NOT EXISTS (
      SELECT 1 FROM school_memberships m WHERE m.school_id=expected_school
        AND m.user_id=NEW.teacher_user_id AND m.role IN ('staff','admin') AND m.is_active
    ) THEN RAISE EXCEPTION 'Timetable teacher must be active in the class school' USING ERRCODE='23514'; END IF;
  ELSIF TG_TABLE_NAME = 'leave_requests' THEN
    SELECT school_id INTO expected_school FROM students WHERE id=NEW.student_id;
    SELECT school_id INTO related_school FROM academic_terms WHERE id=NEW.term_id;
    IF expected_school IS DISTINCT FROM related_school THEN RAISE EXCEPTION 'Leave student and term must belong to one school' USING ERRCODE='23514'; END IF;
  ELSIF TG_TABLE_NAME = 'diary_items' THEN
    SELECT school_id INTO related_school FROM class_sections WHERE id=NEW.class_section_id;
    IF NEW.school_id IS DISTINCT FROM related_school THEN RAISE EXCEPTION 'Diary class must belong to its school' USING ERRCODE='23514'; END IF;
    SELECT school_id INTO related_school FROM academic_terms WHERE id=NEW.term_id;
    IF NEW.school_id IS DISTINCT FROM related_school THEN RAISE EXCEPTION 'Diary term must belong to its school' USING ERRCODE='23514'; END IF;
    IF NEW.subject_id IS NOT NULL THEN
      SELECT school_id INTO related_school FROM subjects WHERE id=NEW.subject_id;
      IF NEW.school_id IS DISTINCT FROM related_school THEN RAISE EXCEPTION 'Diary subject must belong to its school' USING ERRCODE='23514'; END IF;
    END IF;
  ELSIF TG_TABLE_NAME IN ('attendance_registers', 'attendance_submissions') THEN
    SELECT school_id INTO related_school FROM class_sections WHERE id=NEW.class_section_id;
    IF NEW.school_id IS DISTINCT FROM related_school THEN RAISE EXCEPTION 'Attendance register class must belong to its school' USING ERRCODE='23514'; END IF;
    SELECT school_id INTO related_school FROM academic_terms WHERE id=NEW.term_id;
    IF NEW.school_id IS DISTINCT FROM related_school THEN RAISE EXCEPTION 'Attendance register term must belong to its school' USING ERRCODE='23514'; END IF;
  ELSIF TG_TABLE_NAME = 'attendance_record_revisions' THEN
    SELECT school_id INTO related_school FROM students WHERE id=NEW.student_id;
    IF NEW.school_id IS DISTINCT FROM related_school THEN RAISE EXCEPTION 'Attendance revision student must belong to its school' USING ERRCODE='23514'; END IF;
    SELECT school_id INTO related_school FROM class_sections WHERE id=NEW.class_section_id;
    IF NEW.school_id IS DISTINCT FROM related_school THEN RAISE EXCEPTION 'Attendance revision class must belong to its school' USING ERRCODE='23514'; END IF;
  END IF;
  RETURN NEW;
END $$;

DO $$
DECLARE
  relation_name text;
  trigger_name text;
BEGIN
  FOREACH relation_name IN ARRAY ARRAY[
    'enrollments','subject_attendance','attendance_records','timetable_slots',
    'leave_requests','diary_items','attendance_registers','attendance_submissions',
    'attendance_record_revisions'
  ] LOOP
    trigger_name := 'validate_' || relation_name || '_school';
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname=trigger_name) THEN
      EXECUTE format(
        'CREATE CONSTRAINT TRIGGER %I AFTER INSERT OR UPDATE ON %I DEFERRABLE INITIALLY IMMEDIATE FOR EACH ROW EXECUTE FUNCTION validate_school_relationships()',
        trigger_name, relation_name
      );
    END IF;
  END LOOP;
END $$;

REVOKE ALL ON FUNCTION validate_school_relationships() FROM PUBLIC;

-- The browser never talks to Supabase's Data API. Keep public tables closed to
-- anon/authenticated roles when those Supabase roles exist, while the server's
-- direct database role remains the sole application data path.
DO $$
DECLARE
  table_name text;
  protected_tables text[] := ARRAY[
    'users', 'schools', 'school_memberships', 'students', 'parents',
    'guardian_relationships', 'academic_terms', 'class_sections', 'enrollments',
    'subjects', 'subject_attendance', 'attendance_records', 'gate_events',
    'timetable_slots', 'attendance_policies', 'leave_requests', 'leave_documents',
    'leave_audits', 'diary_items', 'diary_acknowledgements', 'homework_completions',
    'diary_notes', 'notifications', 'school_contacts', 'auth_sessions',
    'audit_events', 'ai_conversations', 'ai_messages', 'api_rate_limit_buckets',
    'event_outbox', 'attendance_registers', 'attendance_submissions',
    'attendance_record_revisions', 'school_calendar_days', 'node_schema_migrations'
  ];
BEGIN
  FOREACH table_name IN ARRAY protected_tables LOOP
    IF to_regclass(format('public.%I', table_name)) IS NOT NULL THEN
      EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_name);
      IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        EXECUTE format('REVOKE ALL ON TABLE public.%I FROM anon', table_name);
      END IF;
      IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        EXECUTE format('REVOKE ALL ON TABLE public.%I FROM authenticated', table_name);
      END IF;
    END IF;
  END LOOP;

  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    EXECUTE 'ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON TABLES FROM anon';
    EXECUTE 'ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON SEQUENCES FROM anon';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    EXECUTE 'ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON TABLES FROM authenticated';
    EXECUTE 'ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON SEQUENCES FROM authenticated';
  END IF;
END $$;
