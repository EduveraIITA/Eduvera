function mount(environment: ExecutionEnvironment = { mode: "live" }) {
  const onDone = vi.fn(); const onClose = vi.fn();
  const element = (env: ExecutionEnvironment, schoolId = "campus") => <ExecutionEnvironmentProvider environment={env}><PeopleBulkAddDialog schoolId={schoolId} onDone={onDone} onClose={onClose} /></ExecutionEnvironmentProvider>;
  const view = render(element(environment));
  return { ...view, onDone, onClose, change: (env: ExecutionEnvironment, schoolId = "campus") => view.rerender(element(env, schoolId)) };
}
